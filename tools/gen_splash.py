"""Write core/ui/splash_image.h, the boot screen picture, from integration/radiofoundry/splash/avatar.png.

The DM-32UV's panel shows 16 colors at a time (4 bpp, one palette for the whole frame), and the splash's background,
text, accent, rule and footer take five of them: the picture gets COLORS, Floyd-Steinberg dithered, at SIZE pixels
square (the mark's 132 px on the DM-32: 0.6 x its 220 px visible width). Median cut alone spends them all on the large
grays and browns, so ACCENTS of them are the vivid colors of small areas (the red, the gold): the mean of the bright,
saturated pixels in each of the most common hue slices. Then patch 0024 is made from the tree:

    python3 tools/gen_splash.py && python3 tools/rf_patch.py make 0024-boot-screen-picture.patch core/ui/splash_image.h core/ui/ui_screens.c

Needs Pillow.
"""
import colorsys
from collections import defaultdict
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "integration/radiofoundry/splash/avatar.png"
OUT = ROOT / "build/radiofoundry-p25/core/ui/splash_image.h"
SIZE = 132
COLORS = 11
ACCENTS = 3


def accents(rgb):
    slices = defaultdict(list)
    for c in rgb:
        h, s, v = colorsys.rgb_to_hsv(*(x / 255 for x in c))
        if s > 0.45 and v > 0.5:
            slices[int(h * 20) % 20].append(c)
    top = sorted(slices.values(), key=len, reverse=True)[:ACCENTS]
    return [x for g in top for x in (sum(ch) // len(g) for ch in zip(*g))]


def rgb565(r, g, b):
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def main():
    im = Image.open(SRC).convert("RGB").resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    raw = im.tobytes()
    n = COLORS - ACCENTS
    pal = im.quantize(n, method=Image.Quantize.MEDIANCUT, kmeans=4, dither=Image.Dither.NONE).getpalette()[:3 * n]
    pal += accents(zip(raw[0::3], raw[1::3], raw[2::3]))
    assert len(pal) == 3 * COLORS
    pal = [(c >> 3) << 3 if i % 3 != 1 else (c >> 2) << 2 for i, c in enumerate(pal)]	# as the panel shows them
    pimg = Image.new("P", (1, 1))
    pimg.putpalette(pal + pal[:3] * (256 - COLORS))	# the unused entries repeat entry 0, so they fold back onto it
    px = [p if p < COLORS else 0 for p in im.quantize(palette=pimg, dither=Image.Dither.FLOYDSTEINBERG).tobytes()]
    packed = [px[i] << 4 | px[i + 1] for i in range(0, len(px), 2)]

    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/gen_splash.py from integration/radiofoundry/splash/avatar.png: do not edit",
        "// The boot screen picture: SPLASH_IMG_SIZE square, 4 bits a pixel (high nibble first), indexes into splash_img_pal",
        "#define SPLASH_IMG_SIZE\t%d" % SIZE,
        "static const color_t splash_img_pal[%d] = { %s };" % (
            COLORS, ", ".join("0x%04X" % rgb565(*pal[i:i + 3]) for i in range(0, 3 * COLORS, 3))),
        "static const uint8_t splash_img_px[SPLASH_IMG_SIZE * SPLASH_IMG_SIZE / 2] = {",
    ]
    for i in range(0, len(packed), 24):
        lines.append("\t" + ", ".join("0x%02X" % b for b in packed[i:i + 24]) + ",")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {SIZE}x{SIZE}, {COLORS} colors")


if __name__ == "__main__":
    main()
